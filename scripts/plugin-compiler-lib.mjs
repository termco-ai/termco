/** The existing runtime scheme intentionally exposes module namespaces as a
 * default export. JSX generated by esbuild expects named exports, so bundle a
 * tiny adapter while keeping React's actual runtime application-wide. */
function jsxRuntimeBridge() {
  return {
    name: "termco-jsx-runtime-bridge",
    setup(buildApi) {
      buildApi.onResolve(
        { filter: /^@termco\/jsx\/(?:jsx-runtime|jsx-dev-runtime)$/ },
        (args) => ({ path: args.path, namespace: "termco-jsx" }),
      );
      buildApi.onLoad({ filter: /.*/, namespace: "termco-jsx" }, () => ({
        loader: "js",
        contents: `
          import runtime from "@termco/react/jsx-runtime";
          export const Fragment = runtime.Fragment;
          export const jsx = runtime.jsx;
          export const jsxs = runtime.jsxs;
          export const jsxDEV = runtime.jsxDEV;
        `,
      }));
    },
  };
}

async function sourceIntegrity(root) {
  const hash = createHash("sha256");
  const walk = async (directory) => {
    const entries = await fs.readdir(directory, { withFileTypes: true });
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name === "node_modules" || entry.name === ".termco-cache") continue;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        await walk(path);
      } else if (entry.isFile()) {
        hash.update(relative(root, path).split(sep).join("/"));
        hash.update("\0");
        hash.update(await fs.readFile(path));
        hash.update("\0");
      }
    }
  };
  await walk(root);
  return `sha256-${hash.digest("hex")}`;
}

function inside(root, path) {
  return isPathInside(root, path);
}

export function isPathInside(root, path) {
  const windowsPath =
    usesWindowsPathSemantics(root) || usesWindowsPathSemantics(path);
  const pathApi = windowsPath
    ? win32
    : posix.isAbsolute(root) || posix.isAbsolute(path)
      ? posix
      : { isAbsolute, relative, sep };
  const rel = pathApi.relative(root, path);
  return rel !== ".." &&
    !rel.startsWith(`..${pathApi.sep}`) &&
    !pathApi.isAbsolute(rel);
}

export function resolveImportPath(resolveDirectory, specifier) {
  const windowsPath =
    usesWindowsPathSemantics(resolveDirectory) ||
    usesWindowsPathSemantics(specifier);
  if (windowsPath) return win32.resolve(resolveDirectory, specifier);
  if (posix.isAbsolute(resolveDirectory) || posix.isAbsolute(specifier)) {
    return posix.resolve(resolveDirectory, specifier);
  }
  return resolve(resolveDirectory, specifier);
}

function validEntry(root, entry) {
  const path = resolve(root, entry);
  if (!inside(root, path)) throw new Error(`entrypoint escapes plugin folder: ${entry}`);
  return path;
}

export function isAbsoluteImportPath(specifier) {
  return posix.isAbsolute(specifier) || win32.isAbsolute(specifier);
}

function usesWindowsPathSemantics(path) {
  return win32.isAbsolute(path) && !posix.isAbsolute(path);
}

async function assertNoSymlinks(root, directory = root) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(`${basename(root)}: source-owned plugins cannot contain symbolic links`);
    }
    if (entry.isDirectory()) await assertNoSymlinks(root, path);
  }
}

async function validatePluginSource(inputRoot) {
  // esbuild canonicalizes macOS /var paths to /private/var in resolveDir.
  // Canonicalize the ownership root too so a plugin's own relative imports
  // cannot be rejected merely because its copied source lives in a temp dir.
  const root = await fs.realpath(inputRoot);
  const entryName = basename(root);
  const manifestPath = join(root, "termco-plugin.json");
  for (const required of ["package.json", "src"]) {
    try {
      await fs.stat(join(root, required));
    } catch {
      throw new Error(`${entryName}: real plugin is missing ${required}`);
    }
  }
  await assertNoSymlinks(root);
  let manifest;
  try {
    manifest = JSON.parse(await fs.readFile(manifestPath, "utf8"));
  } catch (error) {
    throw new Error(`cannot read ${manifestPath}: ${error.message}`);
  }
  if (manifest.schemaVersion !== 3) {
    throw new Error(`${entryName}: schemaVersion must be 3`);
  }
  if (!manifest.description || !manifest.category) {
    throw new Error(`${entryName}: description and category are required`);
  }
  if (manifest.transitionalHostImports !== undefined) {
    throw new Error(`${entryName}: transitionalHostImports is not supported`);
  }
  const unknownFields = Object.keys(manifest).filter(
    (field) => !MANIFEST_FIELDS.has(field),
  );
  if (unknownFields.length > 0) {
    throw new Error(
      `${entryName}: unknown manifest field${unknownFields.length === 1 ? "" : "s"}: ${unknownFields.join(", ")}`,
    );
  }
  if (
    !manifest.dependencies ||
    typeof manifest.dependencies !== "object" ||
    Array.isArray(manifest.dependencies)
  ) {
    throw new Error(`${entryName}: dependencies must be an object`);
  }
  const entrypoints = Object.entries(manifest.entrypoints ?? {}).filter(
    ([kind]) => ENTRYPOINTS.includes(kind),
  );
  for (const [, source] of entrypoints) validEntry(root, source);
  for (const asset of manifest.assetBuilds ?? []) {
    validEntry(root, asset.entry);
    if (
      typeof asset.output !== "string" ||
      !asset.output.startsWith("assets/") ||
      !asset.output.endsWith(".mjs")
    ) {
      throw new Error(`${entryName}: asset build output must be assets/*.mjs`);
    }
    validEntry(root, asset.output);
    if (asset.platform !== "node" && asset.platform !== "browser") {
      throw new Error(`${entryName}: asset build platform must be node or browser`);
    }
  }
  if (entrypoints.length > 0 && basename(dirname(root)) === "plugins") {
    // Release archives intentionally omit AGENTS.md. Those files document the
    // source boundary for maintainers; they are not runtime plugin inputs.
    // Repository validation owns that authoring policy, while the compiler
    // accepts the minimal signed source needed by an installed application.
    for (const required of ["README.md"]) {
      try {
        await fs.stat(join(root, required));
      } catch {
        throw new Error(`${entryName}: real plugin is missing ${required}`);
      }
    }
    const sourceEntries = await fs.readdir(join(root, "src"), {
      recursive: true,
    });
    if (!sourceEntries.some((path) => /\.test\.[cm]?[jt]sx?$/.test(path))) {
      throw new Error(`${entryName}: real plugin must own at least one behavior test`);
    }
  }
  const packageJson = await packageManifest(root);
  return { root, manifest, manifestPath, packageJson };
}

export async function discoverPluginSources(pluginsRoot) {
  let entries;
  try {
    entries = await fs.readdir(pluginsRoot, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return [];
    throw error;
  }
  const plugins = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    plugins.push(await validatePluginSource(join(pluginsRoot, entry.name)));
  }
  return plugins;
}

/** Discover and validate one exact source folder without letting a broken
 * sibling prevent an already-selected plugin from being compiled live. */
export async function discoverPluginSource(pluginRoot) {
  return validatePluginSource(resolve(pluginRoot));
}

function packageNameFromSpecifier(specifier) {
  return specifier.startsWith("@")
    ? specifier.split("/").slice(0, 2).join("/")
    : specifier.split("/")[0];
}

function isBasePackage(packageName) {
  return packageName.endsWith("-base");
}

async function packageSourceEntry(packageRoot) {
  const manifest = await packageManifest(packageRoot);
  const exported =
    typeof manifest.exports === "string"
      ? manifest.exports
      : manifest.exports?.["."]?.import ??
        manifest.exports?.["."]?.default ??
        manifest.module ??
        manifest.main;
  if (typeof exported !== "string") {
    throw new Error(`${manifest.name ?? packageRoot}: public package has no export`);
  }
  return validEntry(packageRoot, exported);
}

async function isRuntimePluginPackage(packageRoot) {
  try {
    const manifest = JSON.parse(
      await fs.readFile(join(packageRoot, "termco-plugin.json"), "utf8"),
    );
    return Object.keys(manifest.entrypoints ?? {}).length > 0;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

function ownershipGuard(plugin, options = {}) {
  const dependencies = new Set(Object.keys(plugin.manifest.dependencies ?? {}));
  const publicRoots = new Set();
  return {
    name: "termco-real-plugin-ownership",
    setup(buildApi) {
      buildApi.onResolve({ filter: /.*/ }, async (args) => {
        const specifier = args.path;
        if (specifier.startsWith(".") || isAbsoluteImportPath(specifier)) {
          const candidate = resolveImportPath(args.resolveDir, specifier);
          if (
            !inside(plugin.root, candidate) &&
            ![...publicRoots].some((publicRoot) => inside(publicRoot, candidate))
          ) {
            return {
              errors: [
                {
                  text: `${plugin.manifest.id} imports private source outside its plugin folder: ${specifier}`,
                },
              ],
            };
          }
          return null;
        }
        if (PUBLIC_HOST_PACKAGES.has(specifier)) {
          if (options.nodeEntrypoint) {
            return {
              errors: [
                {
                  text: `${plugin.manifest.id} has runtime import "${specifier}" in a Node entrypoint; use a type-only host import and service identifiers from a declared base package`,
                },
              ],
            };
          }
          return { path: specifier, external: true };
        }
        if (
          specifier.startsWith("node:") ||
          (options.allowTestRuntime &&
            TEST_RUNTIME.has(
              specifier.startsWith("@")
                ? specifier.split("/").slice(0, 2).join("/")
                : specifier.split("/")[0],
            ))
        ) {
          return { path: specifier, external: true };
        }
        const packageName = packageNameFromSpecifier(specifier);
        if (
          PRIVATE_PREFIXES.some((prefix) => specifier.startsWith(prefix)) ||
          (specifier.startsWith("@termco/") && !isBasePackage(packageName))
        ) {
          return {
            errors: [
              {
                text: `${plugin.manifest.id} imports private Termco source "${specifier}"; use a declared base package or @termco/kernel`,
              },
            ],
          };
        }
        if (!dependencies.has(packageName)) {
          return {
            errors: [
              {
                text: `${plugin.manifest.id} imports undeclared dependency "${packageName}"`,
              },
            ],
          };
        }
        let declaredRoot;
        try {
          declaredRoot = await resolveInstalledPackage(
            packageName,
            options.dependencyRoot ?? DEFAULT_DEPENDENCY_ROOT,
            plugin.root,
          );
        } catch (error) {
          if (isBasePackage(packageName)) {
            return { errors: [{ text: error.message }] };
          }
        }
        if (
          /(?:-provider|-consumer)$/.test(packageName) ||
          (declaredRoot && (await isRuntimePluginPackage(declaredRoot)))
        ) {
          return {
            errors: [
              {
                text: `${plugin.manifest.id} imports runtime plugin package "${packageName}"; provider implementation packages cannot be dependencies`,
              },
            ],
          };
        }
        if (isBasePackage(packageName)) {
          publicRoots.add(declaredRoot);
          return { path: await packageSourceEntry(declaredRoot) };
        }
        if (!options.rendererRuntimeDependencies) {
          options.runtimeDependencies?.add(packageName);
        }
        return {
          path: options.rendererRuntimeDependencies
            ? `@termco/${specifier}`
            : specifier,
          external: true,
        };
      });
    },
  };
}

async function packageManifest(packageRoot) {
  return JSON.parse(await fs.readFile(join(packageRoot, "package.json"), "utf8"));
}

async function matchingPackageRoot(candidate, packageName) {
  try {
    const root = await fs.realpath(candidate);
    const manifest = await packageManifest(root);
    return manifest.name === packageName ? root : null;
  } catch {
    return null;
  }
}

async function matchingShippedBaseRoot(packagesRoot, packageName) {
  let entries;
  try {
    entries = await fs.readdir(packagesRoot, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const root = await matchingPackageRoot(
      join(packagesRoot, entry.name),
      packageName,
    );
    if (!root) continue;
    try {
      const manifest = JSON.parse(
        await fs.readFile(join(root, "termco-plugin.json"), "utf8"),
      );
      if (Object.keys(manifest.entrypoints ?? {}).length === 0) return root;
    } catch {}
  }
  return null;
}

async function resolveShippedBasePackage(packageName) {
  if (!isBasePackage(packageName)) return null;
  for (const packagesRoot of SHIPPED_PACKAGE_ROOTS) {
    const root = await matchingShippedBaseRoot(packagesRoot, packageName);
    if (root) return root;
  }
  return null;
}

async function packageRootFromEntry(entry, packageName) {
  let current = dirname(entry);
  while (true) {
    const matched = await matchingPackageRoot(current, packageName);
    if (matched) return matched;
    const parent = dirname(current);
    if (parent === current) return null;
    current = parent;
  }
}

async function resolveInstalledPackage(packageName, dependencyRoot, requesterRoot) {
  const segments = packageName.split("/");
  if (requesterRoot) {
    const requesterManifest = await packageManifest(requesterRoot);
    const requestedRange = {
      ...requesterManifest.optionalDependencies,
      ...requesterManifest.dependencies,
      ...requesterManifest.devDependencies,
    }[packageName];
    if (typeof requestedRange === "string" && requestedRange.startsWith("file:")) {
      const fileDependency = await matchingPackageRoot(
        resolve(requesterRoot, requestedRange.slice("file:".length)),
        packageName,
      );
      if (fileDependency) return fileDependency;
    }
    let current = requesterRoot;
    while (true) {
      const nested = await matchingPackageRoot(
        join(current, "node_modules", ...segments),
        packageName,
      );
      if (nested) return nested;
      if (basename(current) === "node_modules") {
        const sibling = await matchingPackageRoot(
          join(current, ...segments),
          packageName,
        );
        if (sibling) return sibling;
      }
      const parent = dirname(current);
      if (parent === current) break;
      current = parent;
    }
    try {
      const entry = createRequire(join(requesterRoot, "package.json")).resolve(
        packageName,
      );
      const root = await packageRootFromEntry(entry, packageName);
      if (root) return root;
    } catch {}
    try {
      const siblings = await fs.readdir(dirname(requesterRoot), {
        withFileTypes: true,
      });
      for (const sibling of siblings) {
        if (!sibling.isDirectory()) continue;
        const matched = await matchingPackageRoot(
          join(dirname(requesterRoot), sibling.name),
          packageName,
        );
        if (matched) return matched;
      }
    } catch {}
  }
  const direct = await matchingPackageRoot(
    join(dependencyRoot, ...segments),
    packageName,
  );
  if (direct) return direct;
  const shippedBase = await resolveShippedBasePackage(packageName);
  if (shippedBase) return shippedBase;
  throw new Error(
    `declared Node dependency "${packageName}" is not installed under ${dependencyRoot}`,
  );
}

async function copyRuntimePackage({
  packageName,
  dependencyRoot,
  requesterRoot,
  targetNodeModules,
  optional,
  ancestry,
  materialized,
}) {
  if (PLATFORM_NODE_PACKAGES.has(packageName)) return;
  let sourceRoot;
  try {
    sourceRoot = await resolveInstalledPackage(
      packageName,
      dependencyRoot,
      requesterRoot,
    );
  } catch (error) {
    if (optional) return;
    throw error;
  }
  const targetRoot = join(targetNodeModules, ...packageName.split("/"));
  if (materialized.has(targetRoot)) return;
  materialized.add(targetRoot);
  await copyPackageFiles(sourceRoot, targetRoot);

  if (ancestry.has(sourceRoot)) return;
  const nextAncestry = new Set(ancestry).add(sourceRoot);
  const manifest = await packageManifest(sourceRoot);
  for (const dependency of Object.keys(manifest.dependencies ?? {}).sort()) {
    await copyRuntimePackage({
      packageName: dependency,
      dependencyRoot,
      requesterRoot: sourceRoot,
      targetNodeModules: join(targetRoot, "node_modules"),
      optional: false,
      ancestry: nextAncestry,
      materialized,
    });
  }
  for (const dependency of Object.keys(manifest.optionalDependencies ?? {}).sort()) {
    await copyRuntimePackage({
      packageName: dependency,
      dependencyRoot,
      requesterRoot: sourceRoot,
      targetNodeModules: join(targetRoot, "node_modules"),
      optional: true,
      ancestry: nextAncestry,
      materialized,
    });
  }
}

/** Copy a package through Electron's ASAR-aware read APIs. `fs.cp` performs a
 * native lstat traversal and cannot walk virtual app.asar directories, even
 * though readFile/readdir can. Package dependencies are materialized
 * separately below, so a package's own node_modules subtree is omitted here. */
export async function copyPackageFiles(sourceRoot, targetRoot) {
  async function sourceMode(sourcePath, fallbackMode) {
    const normalized = sourcePath.replaceAll("\\", "/").toLowerCase();
    const markerIndex = normalized.lastIndexOf(".asar/");
    if (markerIndex < 0) return fallbackMode;

    const unpackedPath =
      `${sourcePath.slice(0, markerIndex + ".asar".length)}.unpacked` +
      sourcePath.slice(markerIndex + ".asar".length);
    try {
      return (await fs.stat(unpackedPath)).mode;
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      return fallbackMode;
    }
  }

  async function copyDirectory(source, target, packageRoot = false) {
    // ASAR directories report read-only modes. The cache copy must remain
    // writable so dependency folders can be materialized beneath it.
    await fs.mkdir(target, { recursive: true });
    for (const entry of await fs.readdir(source, { withFileTypes: true })) {
      if (packageRoot && entry.name === "node_modules") continue;
      const sourcePath = join(source, entry.name);
      const targetPath = join(target, entry.name);
      if (entry.isDirectory()) {
        await copyDirectory(sourcePath, targetPath);
        continue;
      }
      if (entry.isSymbolicLink()) {
        const resolved = await fs.realpath(sourcePath);
        const resolvedStats = await fs.stat(resolved);
        if (resolvedStats.isDirectory()) {
          await copyDirectory(resolved, targetPath);
        } else {
          const mode = await sourceMode(resolved, resolvedStats.mode);
          await fs.mkdir(dirname(targetPath), { recursive: true });
          await fs.writeFile(targetPath, await fs.readFile(resolved), {
            mode,
          });
          await fs.chmod(targetPath, mode);
        }
        continue;
      }
      if (!entry.isFile()) continue;
      const stats = await fs.stat(sourcePath);
      const mode = await sourceMode(sourcePath, stats.mode);
      await fs.mkdir(dirname(targetPath), { recursive: true });
      await fs.writeFile(targetPath, await fs.readFile(sourcePath), {
        mode,
      });
      await fs.chmod(targetPath, mode);
    }
  }
  await copyDirectory(sourceRoot, targetRoot, true);
}

async function materializeRuntimeDependencies(
  dependencies,
  outputRoot,
  dependencyRoot,
  requesterRoot,
) {
  const targetNodeModules = join(outputRoot, "node_modules");
  const materialized = new Set();
  for (const packageName of [...dependencies].sort()) {
    await copyRuntimePackage({
      packageName,
      dependencyRoot,
      requesterRoot,
      targetNodeModules,
      optional: false,
      ancestry: new Set(),
      materialized,
    });
  }
}

/** Renderer runtime shims expose one default module namespace. Adapt ordinary
 * named and dynamic npm imports emitted by source plugins to that stable host
 * interface, while keeping the plugin's source idiomatic and copyable. */
export function rewriteRendererRuntimeImports(code) {
  let index = 0;
  return code
    .replace(
      /import\(\s*(["'])(@termco\/[^"']+)\1\s*\)/g,
      (_all, quote, specifier) =>
        `import(${quote}${specifier}${quote}).then((module) => module.default)`,
    )
    .replace(
      /import\s*\*\s*as\s*([A-Za-z_$][\w$]*)\s*from\s*["'](@termco\/[^"']+)["'];?/g,
      (_all, local, specifier) => `import ${local} from "${specifier}";`,
    )
    .replace(
      /import\s*\{([^}]*)\}\s*from\s*["'](@termco\/[^"']+)["'];?/g,
      (_all, names, specifier) => {
        const local = `__termco_runtime_${index++}`;
        const bindings = names
          .split(",")
          .map((name) => name.trim())
          .filter(Boolean)
          .map((name) => name.replace(/\s+as\s+/, ": "))
          .join(", ");
        return `import ${local} from "${specifier}";\nconst { ${bindings} } = ${local};`;
      },
    );
}

async function sourceFiles(directory) {
  const files = [];
  const walk = async (current) => {
    const entries = await fs.readdir(current, { withFileTypes: true });
    for (const entry of entries) {
      const path = join(current, entry.name);
      if (entry.isDirectory()) await walk(path);
      else if (entry.isFile() && SOURCE_EXTENSIONS.test(entry.name)) files.push(path);
    }
  };
  await walk(directory);
  return files;
}

/** Compile every readable source file as a temporary entry. This proves that
 * an unused helper, test, or future entrypoint cannot hide a private import
 * outside the plugin boundary merely because today's entrypoint does not reach it. */
async function certifyAllOwnedSource(plugin, dependencyRoot) {
  const sourceRoot = join(plugin.root, "src");
  const entries = await sourceFiles(sourceRoot);
  await build({
    entryPoints: entries,
    outdir: join(plugin.root, ".termco-ownership-check"),
    outbase: sourceRoot,
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node22",
    jsx: "automatic",
    jsxImportSource: "@termco/jsx",
    loader: { ".css": "text" },
    logLevel: "silent",
    plugins: [
      jsxRuntimeBridge(),
      ownershipGuard(plugin, { allowTestRuntime: true, dependencyRoot }),
    ],
  });
}

async function emitContractDeclarations(plugin, outputRoot) {
  const sourceRoot = join(plugin.root, "src");
  const entries = (await sourceFiles(sourceRoot)).filter(
    (path) => !/\.test\.[cm]?[jt]sx?$/.test(path),
  );
  const program = ts.createProgram(entries, {
    declaration: true,
    emitDeclarationOnly: true,
    esModuleInterop: true,
    jsx: ts.JsxEmit.ReactJSX,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    noEmitOnError: false,
    outDir: outputRoot,
    rootDir: sourceRoot,
    skipLibCheck: true,
    target: ts.ScriptTarget.ES2022,
  });
  const syntaxErrors = program
    .getSyntacticDiagnostics()
    .filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
  if (syntaxErrors.length > 0) {
    throw new Error(
      `${plugin.manifest.id}: contract declaration syntax failed: ${ts.flattenDiagnosticMessageText(syntaxErrors[0].messageText, "\n")}`,
    );
  }
  const emitted = program.emit();
  if (emitted.emitSkipped) {
    throw new Error(`${plugin.manifest.id}: contract declarations were not emitted`);
  }
}

async function compileContractPackage(plugin, outputRoot, dependencyRoot) {
  const publicEntry = await packageSourceEntry(plugin.root);
  const outfile = join(outputRoot, "index.mjs");
  await build({
    entryPoints: [publicEntry],
    outfile,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    logLevel: "silent",
    plugins: [ownershipGuard(plugin, { dependencyRoot })],
  });
  await emitContractDeclarations(plugin, outputRoot);
  const types = join(outputRoot, "index.d.ts");
  await fs.writeFile(
    join(outputRoot, "package.json"),
    `${JSON.stringify(
      {
        name: plugin.packageJson.name,
        version: plugin.packageJson.version ?? plugin.manifest.version,
        type: "module",
        exports: { ".": { types: "./index.d.ts", import: "./index.mjs" } },
        dependencies: plugin.packageJson.dependencies ?? {},
      },
      null,
      2,
    )}\n`,
  );
  return { package: outfile, types };
}

async function compilePluginInto(plugin, outputRoot, dependencyRoot) {
  const entrypoints = Object.entries(plugin.manifest.entrypoints ?? {});
  const outputs =
    entrypoints.length === 0
      ? await compileContractPackage(plugin, outputRoot, dependencyRoot)
      : {};
  const runtimeDependencies = new Set();
  for (const [kind, source] of entrypoints) {
    if (!ENTRYPOINTS.includes(kind)) continue;
    const outfile = join(outputRoot, `${kind}.mjs`);
    const result = await build({
      entryPoints: [validEntry(plugin.root, source)],
      outfile,
      bundle: true,
      format: "esm",
      platform: kind === "renderer" ? "browser" : "node",
      target: kind === "renderer" ? "es2022" : "node22",
      jsx: "automatic",
      jsxImportSource: "@termco/jsx",
      loader: { ".css": "text" },
      sourcemap: true,
      metafile: true,
      logLevel: "silent",
      write: false,
      plugins: [
        jsxRuntimeBridge(),
        ownershipGuard(plugin, {
          rendererRuntimeDependencies: kind === "renderer",
          nodeEntrypoint: kind !== "renderer",
          dependencyRoot,
          ...(kind === "renderer" ? {} : { runtimeDependencies }),
        }),
      ],
    });
    for (const file of result.outputFiles) {
      await fs.mkdir(dirname(file.path), { recursive: true });
      await fs.writeFile(
        file.path,
        kind === "renderer" && file.path === outfile
          ? rewriteRendererRuntimeImports(file.text)
          : file.contents,
      );
    }
    outputs[kind] = outfile;
  }
  const assetsRoot = join(plugin.root, "assets");
  try {
    const assets = await fs.stat(assetsRoot);
    if (!assets.isDirectory()) {
      throw new Error(`${plugin.manifest.id}: assets must be a directory`);
    }
    await fs.cp(assetsRoot, join(outputRoot, "assets"), { recursive: true });
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  for (const asset of plugin.manifest.assetBuilds ?? []) {
    const outfile = join(outputRoot, asset.output);
    await fs.mkdir(dirname(outfile), { recursive: true });
    await build({
      entryPoints: [validEntry(plugin.root, asset.entry)],
      outfile,
      bundle: true,
      format: "esm",
      platform: asset.platform,
      target: asset.target ?? (asset.platform === "node" ? "node18" : "es2022"),
      jsx: "automatic",
      jsxImportSource: "@termco/jsx",
      loader: { ".css": "text" },
      sourcemap: true,
      logLevel: "silent",
      plugins: [
        jsxRuntimeBridge(),
        ownershipGuard(plugin, {
          dependencyRoot,
          ...(asset.platform === "node" ? { runtimeDependencies } : {}),
          rendererRuntimeDependencies: asset.platform === "browser",
          nodeEntrypoint: asset.platform === "node",
        }),
      ],
    });
    outputs[asset.output] = outfile;
  }
  await materializeRuntimeDependencies(
    runtimeDependencies,
    outputRoot,
    dependencyRoot,
    plugin.root,
  );
  await fs.writeFile(
    join(outputRoot, "termco-plugin.json"),
    `${JSON.stringify(plugin.manifest, null, 2)}\n`,
  );
  const integrity = await sourceIntegrity(plugin.root);
  await fs.writeFile(join(outputRoot, "integrity.txt"), `${integrity}\n`);
  return { outputs, integrity };
}

export async function compilePlugin(plugin, cacheRoot, options = {}) {
  const dependencyRoot = options.dependencyRoot ?? DEFAULT_DEPENDENCY_ROOT;
  await certifyAllOwnedSource(plugin, dependencyRoot);
  const outputParent = join(cacheRoot, plugin.manifest.id);
  const outputRoot = join(outputParent, plugin.manifest.version);
  await fs.mkdir(outputParent, { recursive: true });
  const stagingRoot = await fs.mkdtemp(
    join(outputParent, `.${plugin.manifest.version}.staging-`),
  );
  let published = false;
  try {
    const { outputs, integrity } = await compilePluginInto(
      plugin,
      stagingRoot,
      dependencyRoot,
    );

    let previousRoot;
    try {
      await fs.stat(outputRoot);
      previousRoot = join(
        outputParent,
        `.${plugin.manifest.version}.previous-${randomUUID()}`,
      );
      await fs.rename(outputRoot, previousRoot);
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    try {
      await fs.rename(stagingRoot, outputRoot);
      published = true;
    } catch (error) {
      if (previousRoot) await fs.rename(previousRoot, outputRoot);
      throw error;
    }
    if (previousRoot) {
      await fs.rm(previousRoot, { recursive: true, force: true });
    }
    const publishedOutputs = Object.fromEntries(
      Object.entries(outputs).map(([name, path]) => [
        name,
        join(outputRoot, relative(stagingRoot, path)),
      ]),
    );
    return {
      pluginId: plugin.manifest.id,
      outputRoot,
      outputs: publishedOutputs,
      integrity,
    };
  } finally {
    if (!published) {
      await fs.rm(stagingRoot, { recursive: true, force: true });
    }
  }
}

export async function compileAllPlugins({ pluginsRoot, cacheRoot, dependencyRoot }) {
  const plugins = await discoverPluginSources(pluginsRoot);
  const results = [];
  for (const plugin of plugins) {
    results.push(await compilePlugin(plugin, cacheRoot, { dependencyRoot }));
  }
  return results;
}
